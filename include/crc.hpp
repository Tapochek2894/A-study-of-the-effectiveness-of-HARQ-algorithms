#pragma once

#include <cstdint>
#include <vector>

namespace harq {

// Модуль CRC: кодирование и декодирование циклических избыточных кодов.
// Реализация на основе полиномиальной арифметики над GF(2).
//
// Алгоритм кодирования (Бурков, раздел 1.2.1):
//   1. Из сообщения m формируется многочлен m(x)
//   2. Вычисляется c(x) = m(x) * x^r mod g(x)
//   3. Кодовое слово a(x) = m(x) * x^r + c(x)
//
// Алгоритм декодирования:
//   1. Принятое сообщение переводится в многочлен b(x)
//   2. Вычисляется синдром s(x) = b(x) mod g(x)
//   3. Если s(x) != 0, ошибка обнаружена
class Crc {
 public:
  // Создает CRC с заданным порождающим многочленом.
  // polynomial - коэффициенты многочлена от старшей степени к младшей.
  // Например, x^3 + x + 1 задается как {1, 0, 1, 1}.
  explicit Crc(const std::vector<uint8_t>& polynomial);

  // Степень порождающего многочлена (количество проверочных бит).
  int r() const;

  // Возвращает порождающий многочлен.
  const std::vector<uint8_t>& polynomial() const;

  // Кодирует сообщение, добавляя r проверочных бит.
  // data - входное сообщение длины k бит.
  // Возвращает кодовое слово длины n = k + r.
  std::vector<uint8_t> Encode(const std::vector<uint8_t>& data) const;

  // Вычисляет синдром для принятого сообщения.
  // codeword - принятое кодовое слово длины n.
  // Возвращает синдром длины r.
  std::vector<uint8_t> ComputeSyndrome(
      const std::vector<uint8_t>& codeword) const;

  // Проверяет, обнаружена ли ошибка в принятом сообщении.
  // Возвращает true, если синдром ненулевой (ошибка обнаружена).
  bool HasError(const std::vector<uint8_t>& codeword) const;

  // Декодирует кодовое слово, извлекая исходное сообщение.
  // codeword - принятое кодовое слово длины n.
  // Возвращает информационную часть длины k = n - r.
  // Примечание: не исправляет ошибки, только извлекает данные.
  std::vector<uint8_t> Decode(const std::vector<uint8_t>& codeword) const;

 private:
  // Вычисляет остаток от деления многочлена на порождающий.
  // dividend - делимое (многочлен).
  // Возвращает остаток степени меньше r.
  std::vector<uint8_t> PolynomialMod(
      const std::vector<uint8_t>& dividend) const;

  std::vector<uint8_t> polynomial_;
  int r_;  // Степень порождающего многочлена
};

}  // namespace harq
